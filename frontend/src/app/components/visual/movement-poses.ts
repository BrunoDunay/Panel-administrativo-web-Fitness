type Point = [number, number];
type Line = Point[];

/** Una postura: dónde está la cabeza, las líneas del cuerpo y, si hay, el implemento. */
export interface Pose {
  head: Point;
  /** Torso, piernas y brazos: cada línea une sus articulaciones en orden. */
  body: Line[];
  /** Barra, polea o plataforma. */
  gear?: Line[];
  /** Pesos vistos de lado (discos o mancuernas). */
  weights?: Point[];
}

/**
 * Un movimiento son dos posturas (inicio y final) con la misma estructura; la animación va de
 * una a otra y regresa, como una repetición. `ground` es lo que no se mueve: piso, banco, barras.
 */
export interface Movement {
  start: Pose;
  end: Pose;
  ground?: Line[];
}

