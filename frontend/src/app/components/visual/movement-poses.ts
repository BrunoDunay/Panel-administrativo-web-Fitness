/** Convierte líneas de puntos en el atributo `d` de un <path>. */
export function toPath(lines: Line[] | undefined): string {
  return (lines ?? []).map((line) => line.map(([x, y], i) => `${i ? 'L' : 'M'}${x} ${y}`).join('')).join('');
}
