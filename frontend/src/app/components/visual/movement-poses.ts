/** Postura con solo lo que cambia respecto a otra. */
const from = (pose: Pose, changes: Partial<Pose>): Pose => ({ ...pose, ...changes });

function pair(start: Pose, changes: Partial<Pose>, ground?: Line[]): Movement {
  return { start, end: from(start, changes), ground };
}

